//! Math / comparison glyphs.

/// Greater-than or equal to (U+2265).
pub const GTE: &str = "\u{2265}";

/// Less-than or equal to (U+2264).
pub const LTE: &str = "\u{2264}";

/// Almost equal to (U+2248).
pub const APPROX: &str = "\u{2248}";

/// Multiplication sign (U+00D7).
pub const TIMES: &str = "\u{00D7}";

/// Minus sign (U+2212) -- not ASCII hyphen-minus.
pub const MINUS: &str = "\u{2212}";

/// Plus-minus sign (U+00B1).
pub const PLUS_MINUS: &str = "\u{00B1}";

/// Greek capital letter delta (U+0394).
pub const DELTA: &str = "\u{0394}";

/// Micro sign (U+00B5).
pub const MICRO: &str = "\u{00B5}";

/// Square root (U+221A).
pub const SQRT: &str = "\u{221A}";

/// Element of (U+2208).
pub const ELEMENT_OF: &str = "\u{2208}";
